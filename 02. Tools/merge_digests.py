"""Merge digest CSV parts (written by AI digest agents) into one-line-per-item tables per county.

Usage: python -I "02. Tools/merge_digests.py" --county Talbot --parts <dir with pc-*.csv, council-*.csv, ...>
Writes <County>/01. Digests/<Name>.csv and <Name>.md for each group:
  pc-*      -> Planning Commission Actions
  council-* -> County Council Land-Use Actions
  preapp-*  -> Pre-Application Projects
  boa-*     -> Board of Appeals Decisions
Rows are de-duplicated and sorted newest first. Source files are linked by name; their text lives in
<County>/Meeting Minutes/<Body>/.
"""
import argparse
import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from common import county_dir, county_name  # noqa: E402

GROUPS = {
    "pc": ("Planning Commission Actions", "date",
           ["date", "item", "applicant_or_sponsor", "location", "request_type", "lots_or_units", "acres",
            "decision", "vote", "key_conditions", "notable", "source_file"]),
    "council": ("County Council Land-Use Actions", "date",
                ["date", "item", "applicant_or_sponsor", "location", "request_type", "decision", "vote",
                 "key_conditions", "notable", "source_file"]),
    "preapp": ("Pre-Application Projects", "date",
               ["date", "project", "applicant", "location", "project_type", "size", "notes", "source_file"]),
    "commissioners": ("County Commissioners Land-Use Actions", "date",
                      ["date", "item", "applicant_or_sponsor", "location", "request_type", "decision", "vote",
                       "key_conditions", "notable", "source_file"]),
    "boam": ("Board of Appeals Actions (from minutes)", "date",
             ["date", "item", "applicant_or_sponsor", "location", "request_type", "decision", "vote",
              "key_conditions", "notable", "source_file"]),
    "tac": ("Technical Advisory Committee Projects", "date",
            ["date", "project", "applicant", "location", "project_type", "size", "notes", "source_file"]),
    "boa": ("Board of Appeals Decisions", "decision_date",
            ["case_no", "decision_date", "applicant", "location", "zoning", "critical_area", "request_type",
             "request", "outcome", "conditions", "notable", "source_file"]),
}


def norm_date(s):
    s = (s or "").strip()
    for pat, fmt in [(r"^\d{4}-\d{2}-\d{2}$", None)]:
        if re.match(pat, s):
            return s
    m = re.search(r"([A-Za-z]+)\.?\s+(\d{1,2}),?\s+(\d{4})", s)
    if m:
        import datetime as dt
        for f in ("%B %d %Y", "%b %d %Y"):
            try:
                return dt.datetime.strptime(f"{m.group(1)} {m.group(2)} {m.group(3)}", f).date().isoformat()
            except ValueError:
                pass
    m = re.search(r"(\d{1,2})[/-](\d{1,2})[/-](\d{2,4})", s)
    if m:
        y = int(m.group(3)) + (2000 if len(m.group(3)) == 2 else 0)
        return f"{y:04d}-{int(m.group(1)):02d}-{int(m.group(2)):02d}"
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--county", required=True)
    ap.add_argument("--parts", required=True)
    a = ap.parse_args()
    out = county_dir(a.county) / "01. Digests"
    out.mkdir(exist_ok=True)
    for prefix, (name, datecol, cols) in GROUPS.items():
        rows, seen = [], set()
        files = sorted(Path(a.parts).glob(f"{prefix}-*.csv"))
        if not files:
            continue
        for f in files:
            with open(f, newline="", errors="replace") as fh:
                for r in csv.DictReader(fh):
                    r = {k.strip(): (v or "").strip() for k, v in r.items() if k}
                    r[datecol] = norm_date(r.get(datecol, ""))
                    key = tuple(r.get(c, "").lower() for c in cols[:4])
                    if key in seen or not any(r.get(c) for c in cols[1:4]):
                        continue
                    seen.add(key)
                    rows.append(r)
        rows.sort(key=lambda r: r.get(datecol, ""), reverse=True)
        with open(out / f"{name}.csv", "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=cols, extrasaction="ignore")
            w.writeheader()
            w.writerows(rows)
        esc = lambda s: s.replace("|", "/").replace("\n", " ")
        md = [f"# {county_name(a.county)} — {name}", "",
              f"*{len(rows)} items, newest first. Generated by AI digest of the source documents — verify "
              "anything important in the source file (text in `Meeting Minutes/`). CSV version alongside.*", "",
              "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        md += ["| " + " | ".join(esc(r.get(c, "")) for c in cols) + " |" for r in rows]
        (out / f"{name}.md").write_text("\n".join(md) + "\n")
        print(f"{name}: {len(rows)} rows from {len(files)} parts")


if __name__ == "__main__":
    main()
